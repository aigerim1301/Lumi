def detect_category(topic: str) -> str:
    """
    Определяет наиболее подходящую категорию по ключевым словам в теме.
    """
    topic_lower = topic.lower()

    # Ключевые слова для категорий
    edu_keywords = [
        'курс', 'учеб', 'школ', 'вуз', 'универ', 'студент', 'лекци', 'заняти',
        'преподав', 'программир', 'код', 'обучен', 'знани', 'диплом', 'python',
        'django', 'урок', 'домашк', 'семинар'
    ]
    service_keywords = [
        'сервис', 'отзыв', 'продукт', 'сайт', 'приложен', 'доставк', 'магаз',
        'покупк', 'клиент', 'поддержк', 'качеств', 'услуг', 'платформ', 'заказ',
        'оплат', 'тариф', 'софт', 'прилож'
    ]
    event_keywords = [
        'мероприят', 'событ', 'конференц', 'митап', 'хакатон', 'праздник',
        'вебинар', 'фестивал', 'встреч', 'воркшоп', 'тренинг', 'ивент',
        'форум', 'слет', 'выставк'
    ]

    for kw in edu_keywords:
        if kw in topic_lower:
            return 'education'

    for kw in service_keywords:
        if kw in topic_lower:
            return 'service'

    for kw in event_keywords:
        if kw in topic_lower:
            return 'event'

    return 'general'


def generate_survey(topic: str) -> dict:
    """
    Генерирует черновик опроса из 6 вопросов на основе заданной темы.

    Если в .env задан AI_API_KEY, код может обращаться к реальной нейросети.
    В текущей конфигурации используется детерминированный движок шаблонов.

    Возвращает словарь:
    {
        'title': str,
        'description': str,
        'category': str,
        'questions': list[dict]
    }
    """
    topic_clean = topic.strip()
    if not topic_clean:
        topic_clean = 'Общий опрос мнений'

    # Проверяем, задан ли внешний ключ к реальному AI
    api_key = os.getenv('AI_API_KEY', '').strip()
    if api_key:
        # Здесь подключается вызов реальной модели LLM (Gemini API, OpenAI)
        # В случае ошибки вызова или отсутствия соединения происходит плавный откат к шаблонам
        pass

    # Выбираем шаблон по ключевым словам
    category = detect_category(topic_clean)
    tpl_data = TEMPLATES.get(category, TEMPLATES['general'])

    # Формируем заголовок и описание с учётом темы автора
    title = f"{tpl_data['title_prefix']}: «{topic_clean}»"
    description = (
        f"Опрос сгенерирован AI-помощником Lumi по теме: «{topic_clean}». "
        f"Содержит 6 вопросов с игровыми механиками (свайп, термометр эмоций, рейтинг, выбор, текст)."
    )

    questions = []
    for idx, q in enumerate(tpl_data['questions']):
        # Адаптируем текст первого вопроса под конкретную тему
        q_text = q['text']
        if q['qtype'] == 'swipe' and topic_clean:
            q_text = f"Считаете ли вы тему «{topic_clean}» важной и полезной?"

        questions.append({
            'order': idx,
            'text': q_text,
            'qtype': q['qtype'],
            'choices': list(q.get('choices', []))
        })

    return {
        'title': title,
        'description': description,
        'category': category,
        'category_name': tpl_data['category_name'],
        'questions': questions
    }
